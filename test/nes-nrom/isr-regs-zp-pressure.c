// Enough work to need several of the NMI's private registers.
__attribute__((interrupt_norecurse("__nmi"))) void nmi(void) {
  uint16_t a = nmi_a, b = nmi_b;
  nmi_a = a * b + (a >> 3);
  nmi_b = b / ((a & 0x7f) | 1);
}

